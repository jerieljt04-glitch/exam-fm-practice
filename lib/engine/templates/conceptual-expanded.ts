import type { DifficultyLevel, SyllabusTopic } from "../../exam-config";
import type { TopicDomain } from "../../types/exam";
import type { AuthoredChoice, QuestionTemplateDefinition } from "./types";

interface ConceptSpec {
  id: string;
  domain: TopicDomain;
  title: string;
  objective: string;
  difficulty: DifficultyLevel;
  topics: SyllabusTopic[];
  question: string;
  correct: string;
  correctWhy: string;
  wrong: Array<[string, string]>;
}

function concept(spec: ConceptSpec): QuestionTemplateDefinition {
  if (spec.wrong.length !== 4) throw new Error(`${spec.id} must author four distractors.`);
  const choices: AuthoredChoice[] = [
    { text: spec.correct, isCorrect: true, explanation: spec.correctWhy },
    ...spec.wrong.map(([text, explanation]) => ({
      text,
      isCorrect: false,
      type: "CALCULATION_DISTRACTOR" as const,
      explanation,
    })),
  ];
  return {
    id: spec.id,
    domain: spec.domain,
    title: spec.title,
    objective: spec.objective,
    difficulty: spec.difficulty,
    topics: spec.topics,
    steps: spec.difficulty === 1 ? 1 : 2,
    generate: () => ({
      kind: "CHOICE",
      questionText: spec.question,
      variables: {},
      choices,
      solutionSteps:
        `**Step 1 — Identify the governing relationship.**\n\n${spec.correctWhy}` +
        (spec.difficulty === 1
          ? ""
          : `\n\n**Step 2 — Apply it to the facts.**\n\nTherefore, ${spec.correct.charAt(0).toLowerCase()}${spec.correct.slice(1)}`),
    }),
  };
}

