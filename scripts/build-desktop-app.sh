#!/bin/bash
#
# Builds "Exam FM Practice.app" — a double-clickable macOS wrapper around the
# Next.js application. The app owns no logic of its own: it starts the same
# production server `npm start` runs, waits for it to answer, and opens the
# browser. Quitting the app stops the server.
#
#   bash scripts/build-desktop-app.sh            # build and install to ~/Applications
#   bash scripts/build-desktop-app.sh --no-install
#   EXAM_FM_PORT=4174 bash scripts/build-desktop-app.sh
#   EXAM_FM_REPO=/path/to/checkout bash scripts/build-desktop-app.sh
#
set -euo pipefail

# The project the app will drive. Defaults to this checkout; override with
# EXAM_FM_REPO to build an app that points at a different working tree.
SCRIPT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO_ROOT="${EXAM_FM_REPO:-$SCRIPT_ROOT}"
APP_NAME="Exam FM Practice"
BUNDLE_ID="com.examfm.practice"
PORT="${EXAM_FM_PORT:-4173}"
# Browser the app opens the page in (bundle id). Helium by default; falls back to the default browser if it is missing.
BROWSER_ID="${EXAM_FM_BROWSER_ID:-net.imput.helium}"
STAGING="$SCRIPT_ROOT/dist/$APP_NAME.app"
INSTALL_DIR="$HOME/Applications"
INSTALL=1
[ "${1:-}" = "--no-install" ] && INSTALL=0

echo "Building $APP_NAME.app"
echo "  repository : $REPO_ROOT"
echo "  port       : $PORT"
echo "  browser    : $BROWSER_ID"

rm -rf "$STAGING"
mkdir -p "$STAGING/Contents/MacOS" "$STAGING/Contents/Resources"

# ---------------------------------------------------------------- Info.plist
cat > "$STAGING/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>$APP_NAME</string>
  <key>CFBundleDisplayName</key><string>$APP_NAME</string>
  <key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
  <key>CFBundleVersion</key><string>1.0</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>exam-fm-practice</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

# ---------------------------------------------------------------------- icon
echo "  generating icon..."
ICONSET="$(mktemp -d)/AppIcon.iconset"
mkdir -p "$ICONSET"
python3 "$SCRIPT_ROOT/scripts/make-icon.py" "$ICONSET/icon_1024.png"
for spec in "16 16x16" "32 16x16@2x" "32 32x32" "64 32x32@2x" "128 128x128" \
            "256 128x128@2x" "256 256x256" "512 256x256@2x" "512 512x512" "1024 512x512@2x"; do
  set -- $spec
  sips -z "$1" "$1" "$ICONSET/icon_1024.png" --out "$ICONSET/icon_$2.png" > /dev/null 2>&1
done
rm "$ICONSET/icon_1024.png"
iconutil -c icns "$ICONSET" -o "$STAGING/Contents/Resources/AppIcon.icns"
rm -rf "$(dirname "$ICONSET")"

# ------------------------------------------------------------------ launcher
cat > "$STAGING/Contents/MacOS/exam-fm-practice" <<LAUNCHER
#!/bin/bash
#
# Launcher for $APP_NAME. Generated by scripts/build-desktop-app.sh —
# edit that script and rebuild rather than editing this file.
#
REPO="$REPO_ROOT"
PORT="$PORT"
BROWSER_ID="$BROWSER_ID"
LAUNCHER
cat >> "$STAGING/Contents/MacOS/exam-fm-practice" <<'LAUNCHER'
URL="http://127.0.0.1:$PORT"
LOG="$HOME/Library/Logs/exam-fm-practice.log"
STATE="$HOME/Library/Application Support/Exam FM Practice"
PIDFILE="$STATE/server.pid"
RUNNING_BUILD="$STATE/running-build-id"
mkdir -p "$(dirname "$LOG")" "$STATE"

# A GUI launch inherits almost no PATH, so borrow the login shell's.
export PATH="$(/bin/zsh -lc 'printf %s "$PATH"' 2>/dev/null):/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin"

say()  { /usr/bin/osascript -e "display notification \"$1\" with title \"Exam FM Practice\"" >/dev/null 2>&1; }
die()  { /usr/bin/osascript -e "display dialog \"$1\" with title \"Exam FM Practice\" buttons {\"OK\"} default button 1 with icon stop" >/dev/null 2>&1; exit 1; }

# Confirm the port is answering *and* that it is this application, so a
# different local server on the same port can never be mistaken for ours.
alive() { /usr/bin/curl -sf --max-time 3 "$URL" 2>/dev/null | /usr/bin/grep -q "Exam FM Practice"; }
port_taken() { /usr/bin/nc -z 127.0.0.1 "$PORT" >/dev/null 2>&1; }
# Open the page in the chosen browser; use the default browser only if it is not installed.
open_page() { /usr/bin/open -b "$BROWSER_ID" "$URL" 2>/dev/null || /usr/bin/open "$URL"; }

{ echo; echo "=== $(date) launch ==="; } >> "$LOG"

[ -d "$REPO" ] || die "The project folder could not be found at:\n\n$REPO\n\nRebuild the app with: npm run app:build"
cd "$REPO" || die "Could not open $REPO"

# True when the build on disk is missing or older than the sources, which is
# what happens after pulling or merging new code.
stale() {
  [ ! -f .next/BUILD_ID ] && return 0
  [ -n "$(find app components lib prisma package.json next.config.mjs tailwind.config.js \
            -newer .next/BUILD_ID -type f -print -quit 2>/dev/null)" ]
}

# A source build can be newer than the server already running on this port.
# Remember which BUILD_ID that server loaded so a later double-click refreshes it.
build_changed() {
  [ ! -f .next/BUILD_ID ] && return 0
  [ ! -f "$RUNNING_BUILD" ] && return 0
  [ "$(cat "$RUNNING_BUILD")" != "$(cat .next/BUILD_ID)" ]
}

# `npm start` forks a child that renames itself to "next-server", so neither
# process is findable by the command line used to launch it. Kill the recorded
# npm pid, then whatever still holds the port.
stop_server() {
  if [ -f "$PIDFILE" ]; then
    kill "$(cat "$PIDFILE" 2>/dev/null)" 2>/dev/null
    rm -f "$PIDFILE"
  fi
  for _ in $(seq 1 10); do port_taken || return 0; sleep 1; done
  for pid in $(/usr/sbin/lsof -ti "tcp:$PORT" 2>/dev/null); do kill "$pid" 2>/dev/null; done
  for _ in $(seq 1 10); do port_taken || return 0; sleep 1; done
}

# The server outlives this launcher, so a click while it is already up simply
# reopens the page. This script must exit rather than stay resident: macOS will
# not re-run a running app's executable when its Dock icon is clicked, and this
# app has no window to activate.
if alive; then
  if stale || build_changed; then
    # New code has landed since the running server started; replace it rather
    # than silently serving the previous build.
    echo "sources are newer than the running build; restarting" >> "$LOG"
    say "Updating to the latest version…"
    stop_server
  else
    echo "server already running; reopening $URL" >> "$LOG"
    open_page
    exit 0
  fi
fi

port_taken && die "Port $PORT is in use by another program, so the exam server cannot start.\n\nClose it, or rebuild on a different port:\n\nEXAM_FM_PORT=4174 npm run app:build"

command -v node >/dev/null 2>&1 || die "Node.js was not found.\n\nInstall it from nodejs.org, then reopen this app."

if [ ! -d node_modules ]; then
  say "First run — installing dependencies…"
  npm install >> "$LOG" 2>&1 || die "Dependency installation failed.\n\nSee $LOG"
fi

if stale; then
  say "Preparing the exam platform — this takes about a minute…"
  npm run build >> "$LOG" 2>&1 || die "The build failed.\n\nSee $LOG"
fi


# Detach the server so it survives this launcher exiting.
nohup npm start -- --port "$PORT" >> "$LOG" 2>&1 &
SERVER_PID=$!
disown "$SERVER_PID" 2>/dev/null || true
echo "$SERVER_PID" > "$PIDFILE"
cp .next/BUILD_ID "$RUNNING_BUILD"

for _ in $(seq 1 90); do
  alive && break
  kill -0 "$SERVER_PID" 2>/dev/null || die "The server stopped unexpectedly.\n\nSee $LOG"
  sleep 1
done

if ! alive; then
  kill "$SERVER_PID" 2>/dev/null
  die "The server did not start within 90 seconds.\n\nSee $LOG"
fi

echo "server ready on $PORT (pid $SERVER_PID)" >> "$LOG"
open_page
LAUNCHER

chmod +x "$STAGING/Contents/MacOS/exam-fm-practice"
touch "$STAGING"

echo "  built: $STAGING"

if [ "$INSTALL" = "1" ]; then
  mkdir -p "$INSTALL_DIR"
  rm -rf "$INSTALL_DIR/$APP_NAME.app"
  cp -R "$STAGING" "$INSTALL_DIR/$APP_NAME.app"
  touch "$INSTALL_DIR/$APP_NAME.app"
  echo "  installed: $INSTALL_DIR/$APP_NAME.app"
  DESKTOP_LINK="$HOME/Desktop/$APP_NAME.app"
  if [ -L "$DESKTOP_LINK" ]; then rm -f "$DESKTOP_LINK"; fi
  if [ ! -e "$DESKTOP_LINK" ]; then
    ln -s "$INSTALL_DIR/$APP_NAME.app" "$DESKTOP_LINK"
    echo "  shortcut : $DESKTOP_LINK"
  fi
fi

echo "Done."
