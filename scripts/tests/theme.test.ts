/**
 * Design tokens: WCAG AA contrast in both modes, and the token → CSS variable
 * mapping the Tailwind config relies on.
 */
import { readFileSync } from "fs";
import path from "path";

import { PALETTE, THEME_MODES, contrast, cssVariables, hexToHslChannels } from "../../lib/theme/tokens";
import { expect, test } from "./harness";

/** [label, foreground, background, minimum ratio] — 4.5 for text, 3 for large text and UI outlines. */
function pairs(mode: (typeof THEME_MODES)[number]): Array<[string, string, string, number]> {
  const p = PALETTE[mode];
  const surfaces: Array<[string, string]> = [
    ["canvas", p.canvas],
    ["surface", p.surface],
    ["surfaceAlt", p.surfaceAlt],
    ["elevated", p.elevated],
  ];
  const out: Array<[string, string, string, number]> = [];
  for (const [name, bg] of surfaces) {
    out.push([`text on ${name}`, p.textPrimary, bg, 4.5]);
    out.push([`secondary text on ${name}`, p.textSecondary, bg, 4.5]);
    out.push([`link (primary ink) on ${name}`, p.onPrimaryContainer, bg, 4.5]);
    out.push([`success ink on ${name}`, p.successInk, bg, 4.5]);
    out.push([`warning ink on ${name}`, p.warningInk, bg, 4.5]);
    out.push([`danger ink on ${name}`, p.dangerInk, bg, 4.5]);
  }
  out.push(["label on primary button", p.onPrimary, p.primary, 4.5]);
  out.push(["label on tonal button", p.onPrimaryContainer, p.primaryContainer, 4.5]);
  out.push(["label on danger button", p.onDanger, p.dangerInk, 4.5]);
  out.push(["success chip", p.successInk, p.successContainer, 4.5]);
  out.push(["warning chip", p.warningInk, p.warningContainer, 4.5]);
  out.push(["danger chip", p.dangerInk, p.dangerContainer, 4.5]);
  out.push(["neutral chip", p.textPrimary, p.chip, 4.5]);
  out.push(["secondary text on neutral chip", p.textSecondary, p.chip, 4.5]);
  out.push(["focus ring against canvas", p.primary, p.canvas, 3]);
  out.push(["text-field outline on hover", p.borderStrong, p.elevated, 3]);
  return out;
}

test("theme: every text/background pairing meets WCAG AA in light and dark mode", () => {
  for (const mode of THEME_MODES) {
    for (const [label, fg, bg, min] of pairs(mode)) {
      const ratio = contrast(fg, bg);
      expect(ratio >= min, `${mode}: ${label} is ${ratio.toFixed(2)}:1 (needs ${min}:1)`);
    }
  }
});

test("theme: tokens map to CSS variables and HSL channels round-trip", () => {
  for (const mode of THEME_MODES) {
    const vars = cssVariables(mode);
    expect(vars["--g-bg-canvas"] === PALETTE[mode].canvas, `${mode}: canvas variable`);
    expect(vars["--g-accent-primary"] === PALETTE[mode].primary, `${mode}: primary variable`);
    expect(vars["--primary"] === hexToHslChannels(PALETTE[mode].primary), `${mode}: primary channels`);
    for (const [name, value] of Object.entries(vars)) expect(value.length > 0, `${mode}: ${name} empty`);
  }
  expect(hexToHslChannels("#1A73E8") === "214.1 81.7% 50.6%", `#1A73E8 → ${hexToHslChannels("#1A73E8")}`);
  expect(hexToHslChannels("#FFFFFF") === "0.0 0.0% 100.0%", "white channels");
});

test("theme: the stylesheet hard-codes no colours (tokens are the only source)", () => {
  const css = readFileSync(path.join(__dirname, "..", "..", "app", "globals.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  const hex = css.match(/#[0-9a-fA-F]{3,8}\b/g) ?? [];
  expect(hex.length === 0, `hard-coded colours in globals.css: ${hex.join(", ")}`);
});

test("theme: every text-* colour class the components use is generated by the Tailwind theme", () => {
  // Overriding a colour group for text utilities replaces the whole group, so every
  // sub-key the components use (text-primary-foreground, …) must be re-declared.
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const config = require("../../tailwind.config").default as { theme: { extend: { colors: Record<string, unknown>; textColor: Record<string, unknown> } } };
  const { colors, textColor } = config.theme.extend;
  const keys = (group: unknown, name: string): string[] =>
    typeof group === "string" ? [name] : Object.keys(group as object).map((k) => (k === "DEFAULT" ? name : `${name}-${k}`));
  const available = new Set<string>();
  for (const [name, group] of Object.entries(colors)) if (!(name in textColor)) keys(group, name).forEach((k) => available.add(k));
  for (const [name, group] of Object.entries(textColor)) keys(group, name).forEach((k) => available.add(k));
  const root = path.join(__dirname, "..", "..");
  const files = ["components", "app"].flatMap((dir) => walk(path.join(root, dir))).filter((f) => f.endsWith(".tsx"));
  const used = new Set<string>();
  for (const file of files) for (const m of readFileSync(file, "utf8").matchAll(/(?<![\w-])text-((?:primary|success|warning|destructive)(?:-[a-z-]+)?)(?:\/[\d.[\]]+)?(?![\w-])/g)) used.add(m[1]);
  const missing = [...used].filter((k) => !available.has(k));
  expect(missing.length === 0, `text colour classes with no theme colour: ${missing.join(", ")}`);
});

function walk(dir: string): string[] {
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const { readdirSync, statSync } = require("fs") as typeof import("fs");
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}
